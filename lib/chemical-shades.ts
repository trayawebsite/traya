/** Neutral chip for anything we genuinely can't classify. */
const FALLBACK_HEX = '#B9B9B9';

/**
 * Display colour for a shade. Exact name match first (covers the full approved
 * 247-shade list), then a keyword match on the name, then the colour-index
 * reference (e.g. "Reactive Blue 25" → blue), then a neutral chip.
 */
export function shadeHex(name: string, colourIndex?: string): string {
  const n = name.toLowerCase().replace(/\s+/g, ' ').trim();
  const exact = SHADE_HEX[n];
  if (exact) return exact;

  for (const [kw, hex] of KEYWORD_HEX) if (n.includes(kw)) return hex;

  if (colourIndex) {
    const ci = colourIndex.toLowerCase();
    for (const [kw, hex] of KEYWORD_HEX) if (ci.includes(kw)) return hex;
  }

  return FALLBACK_HEX;
}

/**
 * True when the shade has no meaningful colour of its own (resins, binders) —
 * those render as a spec card rather than a colour swatch.
 */
export function isColourless(name: string, categorySlug?: string): boolean {
  if (categorySlug === 'paint-resins') return true;
  const n = name.toLowerCase();
  return n.includes('alkyd') || n.includes('maleic resin');
}
